#!/bin/sh
# Create or reuse a local PostgreSQL container for Workbench development and write
# an env file for ./scripts/dev.sh --config. The password is never printed.
set -eu

repo_root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)

container=${WORKBENCH_PG_CONTAINER:-workbench-pg-dev}
volume=${WORKBENCH_PG_VOLUME:-}
image=${WORKBENCH_PG_IMAGE:-postgres:17-alpine}
port=${WORKBENCH_PG_PORT:-5432}
db_name=${WORKBENCH_PG_DB:-workbench}
db_user=${WORKBENCH_PG_USER:-workbench}
env_file=${WORKBENCH_PG_ENV_FILE:-$repo_root/.env.dev-pg}
data_path=${WORKBENCH_PG_DATA:-$repo_root/.workbench/dev-pg/data.db}
timeout=${WORKBENCH_PG_TIMEOUT:-60}
force=0
destroy=0
yes=0
port_explicit=0
label=io.workbench.dev-db=1
marker="# Generated by scripts/db-init.sh"

usage() {
    cat <<USAGE
Usage: ./scripts/db-init.sh [options]

Create (or reuse) a PostgreSQL container for Workbench development, wait until it
accepts connections and write an env file for ./scripts/dev.sh --config.

Options:
  --name NAME       Container name (default: workbench-pg-dev; env WORKBENCH_PG_CONTAINER)
  --volume NAME     Data volume (default: <name>-data; env WORKBENCH_PG_VOLUME)
  --port PORT       Host port, published on 127.0.0.1 only (default: 5432; env WORKBENCH_PG_PORT)
  --db NAME         Database name (default: workbench; env WORKBENCH_PG_DB)
  --user NAME       Database user (default: workbench; env WORKBENCH_PG_USER)
  --image IMAGE     Image (default: postgres:17-alpine, same as compose.yaml; env WORKBENCH_PG_IMAGE)
  --env-file PATH   Env file to write (default: .env.dev-pg in the repository; env WORKBENCH_PG_ENV_FILE)
  --data PATH       WORKBENCH_DATA for local runtime files (default: .workbench/dev-pg/data.db)
  --timeout SEC     Seconds to wait for pg_isready (default: 60)
  --force           Rewrite an existing env file
  --destroy         Remove the container, its volume and the generated env file
  --yes             Confirm --destroy; without it nothing is removed
  -h, --help        Show this help

Running the script again reuses the container and the password in the env file.
USAGE
}

fail() {
    echo "db-init: $*" >&2
    exit 1
}

need_value() {
    if [ "$#" -lt 2 ] || [ -z "$2" ]; then
        fail "$1 requires a value"
    fi
}

while [ "$#" -gt 0 ]; do
    case $1 in
        --name) need_value "$@"; container=$2; shift 2 ;;
        --name=*) container=${1#*=}; shift ;;
        --volume) need_value "$@"; volume=$2; shift 2 ;;
        --volume=*) volume=${1#*=}; shift ;;
        --port) need_value "$@"; port=$2; port_explicit=1; shift 2 ;;
        --port=*) port=${1#*=}; port_explicit=1; shift ;;
        --db) need_value "$@"; db_name=$2; shift 2 ;;
        --db=*) db_name=${1#*=}; shift ;;
        --user) need_value "$@"; db_user=$2; shift 2 ;;
        --user=*) db_user=${1#*=}; shift ;;
        --image) need_value "$@"; image=$2; shift 2 ;;
        --image=*) image=${1#*=}; shift ;;
        --env-file) need_value "$@"; env_file=$2; shift 2 ;;
        --env-file=*) env_file=${1#*=}; shift ;;
        --data) need_value "$@"; data_path=$2; shift 2 ;;
        --data=*) data_path=${1#*=}; shift ;;
        --timeout) need_value "$@"; timeout=$2; shift 2 ;;
        --timeout=*) timeout=${1#*=}; shift ;;
        --force) force=1; shift ;;
        --destroy|--reset) destroy=1; shift ;;
        --yes|-y) yes=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) usage >&2; fail "unknown option: $1" ;;
    esac
done

[ -n "$volume" ] || volume="$container-data"
case $port in
    ''|*[!0-9]*) fail "--port must be a number from 1 to 65535" ;;
esac
if [ "$port" -lt 1 ] || [ "$port" -gt 65535 ]; then
    fail "--port must be a number from 1 to 65535"
fi
case $timeout in
    ''|*[!0-9]*) fail "--timeout must be a number of seconds" ;;
esac
for value in "$db_name" "$db_user"; do
    case $value in
        ''|*[!A-Za-z0-9_]*) fail "--db and --user may contain only letters, digits and underscores" ;;
    esac
done
case $env_file in
    /*) ;;
    *) env_file="$PWD/$env_file" ;;
esac

command -v docker >/dev/null 2>&1 || fail "docker is not installed or not in PATH"
docker info >/dev/null 2>&1 || fail "cannot reach the Docker daemon; start Docker or check permissions (docker info)"

container_state() {
    docker container inspect -f '{{.State.Status}}' "$container" 2>/dev/null || true
}

container_owned() {
    [ "$(docker container inspect -f '{{index .Config.Labels "io.workbench.dev-db"}}' "$container" 2>/dev/null || true)" = 1 ]
}

volume_exists() {
    docker volume inspect "$volume" >/dev/null 2>&1
}

volume_owned() {
    [ "$(docker volume inspect -f '{{index .Labels "io.workbench.dev-db"}}' "$volume" 2>/dev/null || true)" = 1 ]
}

env_file_generated() {
    [ -f "$env_file" ] && head -n 1 "$env_file" | grep -q "^$marker"
}

if [ "$destroy" -eq 1 ]; then
    state=$(container_state)
    echo "db-init: --destroy removes:"
    found=0
    if [ -n "$state" ]; then echo "  container $container ($state)"; found=1; fi
    if volume_exists; then echo "  volume $volume (all database data)"; found=1; fi
    if env_file_generated; then echo "  env file $env_file"; found=1; fi
    [ "$found" -eq 1 ] || echo "  (nothing found)"
    if [ "$yes" -ne 1 ]; then
        echo "db-init: nothing removed; add --yes to confirm." >&2
        exit 1
    fi
    if [ -n "$state" ]; then
        container_owned || fail "container $container was not created by db-init.sh; refusing to remove it"
        docker rm -f "$container" >/dev/null
        echo "db-init: removed container $container"
    fi
    if volume_exists; then
        volume_owned || fail "volume $volume was not created by db-init.sh; refusing to remove it"
        docker volume rm "$volume" >/dev/null
        echo "db-init: removed volume $volume"
    fi
    if env_file_generated; then
        rm -f "$env_file"
        echo "db-init: removed $env_file"
    elif [ -e "$env_file" ]; then
        echo "db-init: kept $env_file (not generated by this script)"
    fi
    echo "db-init: local runtime files under $(dirname -- "$data_path") were kept."
    exit 0
fi

password_from_env_file() {
    sed -n 's#^WORKBENCH_DATABASE_URL=postgresql://[^:]*:\([A-Za-z0-9]*\)@.*#\1#p' "$env_file" | head -n 1
}

port_in_use() {
    if command -v ss >/dev/null 2>&1; then
        ss -Hltn "( sport = :$1 )" 2>/dev/null | grep -q .
    elif command -v lsof >/dev/null 2>&1; then
        lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1
    else
        return 1
    fi
}

state=$(container_state)
password=
if [ -n "$state" ] && ! container_owned; then
    fail "container $container exists but was not created by db-init.sh; choose another --name"
fi
if [ -z "$state" ] && volume_exists && ! volume_owned; then
    fail "volume $volume exists but was not created by db-init.sh; choose another --volume"
fi
if [ -n "$state" ] || volume_exists; then
    # Existing database: the password lives in the volume, so reuse the one from the env file.
    if [ ! -f "$env_file" ]; then
        fail "container or volume for $container exists but $env_file is missing.
  Pass the env file that was generated for it with --env-file, or recreate the database
  (deletes its data): ./scripts/db-init.sh --name $container --destroy --yes"
    fi
    password=$(password_from_env_file)
    [ -n "$password" ] || fail "$env_file has no WORKBENCH_DATABASE_URL written by db-init.sh; pass the matching --env-file"
elif [ -e "$env_file" ] && [ "$force" -ne 1 ]; then
    fail "$env_file already exists but container $container does not; use --force to replace it or --env-file to choose another file"
fi

if [ -n "$state" ]; then
    published=$(docker container inspect -f '{{range $p, $b := .HostConfig.PortBindings}}{{if eq $p "5432/tcp"}}{{range $b}}{{.HostPort}}{{end}}{{end}}{{end}}' "$container")
    if [ "$port_explicit" -eq 1 ] && [ "$published" != "$port" ]; then
        fail "container $container publishes port ${published:-none}, not $port; drop --port or use another --name"
    fi
    port=$published
    if [ "$state" != running ]; then
        echo "db-init: starting existing container $container..."
        docker start "$container" >/dev/null
    else
        echo "db-init: reusing running container $container"
    fi
else
    if port_in_use "$port"; then
        fail "port $port on this host is already in use; choose a free port with --port"
    fi
    if [ -z "$password" ]; then
        password=$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 32)
        [ "${#password}" -eq 32 ] || fail "could not generate a random password"
    fi
    volume_exists || docker volume create --label "$label" "$volume" >/dev/null
    echo "db-init: creating container $container ($image, 127.0.0.1:$port)..."
    # The password reaches docker through the environment, not the command line.
    if ! POSTGRES_PASSWORD=$password docker run -d --name "$container" \
        --label "$label" \
        --restart unless-stopped \
        -e POSTGRES_DB="$db_name" \
        -e POSTGRES_USER="$db_user" \
        -e POSTGRES_PASSWORD \
        -p "127.0.0.1:$port:5432" \
        -v "$volume:/var/lib/postgresql/data" \
        "$image" >/dev/null; then
        docker rm -f "$container" >/dev/null 2>&1 || true
        fail "docker run failed; if the port is taken, choose another with --port"
    fi
fi

echo "db-init: waiting for PostgreSQL (up to ${timeout}s)..."
elapsed=0
until docker exec "$container" pg_isready -q -h 127.0.0.1 -p 5432 -U "$db_user" -d "$db_name" >/dev/null 2>&1; do
    if [ "$(container_state)" != running ]; then
        docker logs --tail 20 "$container" >&2 || true
        fail "container $container stopped while starting"
    fi
    if [ "$elapsed" -ge "$timeout" ]; then
        fail "PostgreSQL was not ready after ${timeout}s; inspect: docker logs $container"
    fi
    sleep 1
    elapsed=$((elapsed + 1))
done
echo "db-init: PostgreSQL is ready on 127.0.0.1:$port"

if [ -e "$env_file" ] && [ "$force" -ne 1 ]; then
    echo "db-init: kept existing $env_file"
else
    mkdir -p "$(dirname -- "$env_file")"
    tmp_file="$env_file.tmp.$$"
    trap 'rm -f "$tmp_file"' EXIT HUP INT TERM
    (
        umask 077
        cat >"$tmp_file" <<ENV
$marker for container $container. Contains a password; keep it private.
# Use: ./scripts/dev.sh --config $env_file [workbench options]
# Native processes reach PostgreSQL on 127.0.0.1; inside Compose the host is \`postgres\`.
WORKBENCH_DB_DRIVER=postgres
WORKBENCH_DATABASE_URL=postgresql://$db_user:$password@127.0.0.1:$port/$db_name?sslmode=disable
# Local runtime files (OpenD, chart cache) for this workspace.
WORKBENCH_DATA=$data_path
# WORKBENCH_AUTH=password
# WORKBENCH_LISTEN=127.0.0.1:9091
# WORKBENCH_DEV_PORT=9090
# WORKBENCH_PUBLIC_URL=https://dev.example.com
# WORKBENCH_ALLOWED_HOSTS=dev.example.com
# WORKBENCH_LOG_LEVEL=debug
ENV
    )
    chmod 600 "$tmp_file"
    mv "$tmp_file" "$env_file"
    trap - EXIT HUP INT TERM
    echo "db-init: wrote $env_file (mode 600)"
fi
case $env_file in
    "$repo_root"/*)
        if command -v git >/dev/null 2>&1 && ! git -C "$repo_root" check-ignore -q "$env_file"; then
            echo "db-init: warning: $env_file is not ignored by Git; do not commit it" >&2
        fi
        ;;
esac

cat <<NEXT

Next steps:
  ./scripts/dev.sh --config $env_file --print-config
  ./scripts/dev.sh --config $env_file -auth password -listen 127.0.0.1:9091 \\
    -allowed-host w.vm2.de5.net -public-url https://w.vm2.de5.net --web-port 9090

This is a new, empty workspace. The first start in password mode prints the initial
password once in the log; data from SQLite workspaces is not copied.
Remove everything later with:
  ./scripts/db-init.sh --name $container --env-file $env_file --destroy --yes
NEXT
