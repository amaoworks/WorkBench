#!/bin/sh
# Manage a local PostgreSQL container for Workbench development and the env file
# used by ./scripts/dev.sh --config. The database password is never printed.
set -eu

repo_root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)

container=${WORKBENCH_PG_CONTAINER:-workbench-pg-dev}
volume=${WORKBENCH_PG_VOLUME:-}
image=${WORKBENCH_PG_IMAGE:-postgres:17-alpine}
port=${WORKBENCH_PG_PORT:-5432}
db_name=${WORKBENCH_PG_DB:-workbench}
db_user=${WORKBENCH_PG_USER:-workbench}
env_file=${WORKBENCH_PG_ENV_FILE:-$repo_root/.env.dev-pg}
data_path=${WORKBENCH_PG_DATA:-$repo_root/.workbench/dev-pg/data.db}
timeout=${WORKBENCH_PG_TIMEOUT:-60}
auth=password
listen=127.0.0.1:9091
web_port=9090
public_url=
allowed_hosts=
settings_given=0
force=0
yes=0
port_explicit=0
command=
label=io.workbench.dev-db=1
marker="# Generated by scripts/db-manage.sh"

usage() {
    cat <<USAGE
Usage: ./scripts/db-manage.sh COMMAND [options]

Manage a PostgreSQL container for Workbench development.

Commands:
  init      Create (or reuse) the container and volume, wait until ready, write the env file
  start     Start the existing container and wait until ready
  stop      Stop the container; data is kept
  status    Show container, port, volume and env file state (no secrets)
  uninit    Remove the container, volume and generated env file (asks for confirmation)
  help      Show this help

Database options (all commands):
  --name NAME       Container name (default: workbench-pg-dev; env WORKBENCH_PG_CONTAINER)
  --volume NAME     Data volume (default: <name>-data; env WORKBENCH_PG_VOLUME)
  --port PORT       Host port, published on 127.0.0.1 only (default: 5432; env WORKBENCH_PG_PORT)
  --env-file PATH   Env file (default: .env.dev-pg in the repository; env WORKBENCH_PG_ENV_FILE)
  --timeout SEC     Seconds to wait for pg_isready (default: 60)

init options:
  --db NAME, --user NAME, --image IMAGE   Database, user, image (default: workbench, workbench, postgres:17-alpine)
  --data PATH          WORKBENCH_DATA for local runtime files (default: .workbench/dev-pg/data.db)
  --public-url URL     WORKBENCH_PUBLIC_URL; its host is also written to WORKBENCH_ALLOWED_HOSTS
  --allowed-host LIST  WORKBENCH_ALLOWED_HOSTS, comma-separated
  --listen ADDR        WORKBENCH_LISTEN (default: 127.0.0.1:9091)
  --web-port PORT      WORKBENCH_DEV_WEB_PORT (default: 9090)
  --auth MODE          WORKBENCH_AUTH (default: password)
  --force              Rewrite an existing env file; the existing password is kept

uninit options:
  --yes             Confirm without a prompt (required when stdin is not a terminal)
USAGE
}

fail() {
    echo "db-manage: $*" >&2
    exit 1
}

say() {
    echo "db-manage: $*"
}

need_value() {
    if [ "$#" -lt 2 ] || [ -z "$2" ]; then
        fail "$1 requires a value"
    fi
}

while [ "$#" -gt 0 ]; do
    case $1 in
        --name) need_value "$@"; container=$2; shift 2 ;;
        --name=*) container=${1#*=}; shift ;;
        --volume) need_value "$@"; volume=$2; shift 2 ;;
        --volume=*) volume=${1#*=}; shift ;;
        --port) need_value "$@"; port=$2; port_explicit=1; shift 2 ;;
        --port=*) port=${1#*=}; port_explicit=1; shift ;;
        --db) need_value "$@"; db_name=$2; shift 2 ;;
        --db=*) db_name=${1#*=}; shift ;;
        --user) need_value "$@"; db_user=$2; shift 2 ;;
        --user=*) db_user=${1#*=}; shift ;;
        --image) need_value "$@"; image=$2; shift 2 ;;
        --image=*) image=${1#*=}; shift ;;
        --env-file) need_value "$@"; env_file=$2; shift 2 ;;
        --env-file=*) env_file=${1#*=}; shift ;;
        --data) need_value "$@"; data_path=$2; shift 2 ;;
        --data=*) data_path=${1#*=}; shift ;;
        --timeout) need_value "$@"; timeout=$2; shift 2 ;;
        --timeout=*) timeout=${1#*=}; shift ;;
        --public-url) need_value "$@"; public_url=$2; settings_given=1; shift 2 ;;
        --public-url=*) public_url=${1#*=}; settings_given=1; shift ;;
        --allowed-host) need_value "$@"; allowed_hosts=$2; settings_given=1; shift 2 ;;
        --allowed-host=*) allowed_hosts=${1#*=}; settings_given=1; shift ;;
        --listen) need_value "$@"; listen=$2; settings_given=1; shift 2 ;;
        --listen=*) listen=${1#*=}; settings_given=1; shift ;;
        --web-port) need_value "$@"; web_port=$2; settings_given=1; shift 2 ;;
        --web-port=*) web_port=${1#*=}; settings_given=1; shift ;;
        --auth) need_value "$@"; auth=$2; settings_given=1; shift 2 ;;
        --auth=*) auth=${1#*=}; settings_given=1; shift ;;
        --force) force=1; shift ;;
        --yes|-y) yes=1; shift ;;
        -h|--help|help) usage; exit 0 ;;
        -*) usage >&2; fail "unknown option: $1" ;;
        *)
            [ -z "$command" ] || fail "unexpected argument: $1"
            command=$1
            shift
            ;;
    esac
done

case $command in
    init|start|stop|status|uninit) ;;
    '') usage >&2; fail "missing command" ;;
    *) usage >&2; fail "unknown command: $command" ;;
esac

[ -n "$volume" ] || volume="$container-data"
check_port() {
    case $2 in
        ''|*[!0-9]*) fail "$1 must be a number from 1 to 65535" ;;
    esac
    if [ "$2" -lt 1 ] || [ "$2" -gt 65535 ]; then
        fail "$1 must be a number from 1 to 65535"
    fi
}
check_port --port "$port"
check_port --web-port "$web_port"
case $timeout in
    ''|*[!0-9]*) fail "--timeout must be a number of seconds" ;;
esac
for value in "$db_name" "$db_user"; do
    case $value in
        ''|*[!A-Za-z0-9_]*) fail "--db and --user may contain only letters, digits and underscores" ;;
    esac
done
case $auth in
    local|password) ;;
    *) fail "--auth must be local or password" ;;
esac
if ! printf '%s\n' "$listen" | grep -Eq '^[][A-Za-z0-9.:-]*:[0-9]+$'; then
    fail "--listen must be host:port, for example 127.0.0.1:9091"
fi
if [ -n "$public_url" ]; then
    if ! printf '%s\n' "$public_url" | grep -Eq '^https?://[A-Za-z0-9.-]+(:[0-9]+)?/?$'; then
        fail "--public-url must be an origin such as https://dev.example.com (no path)"
    fi
    public_url=${public_url%/}
    if [ -z "$allowed_hosts" ]; then
        allowed_hosts=${public_url#*://}
    fi
fi
if [ -n "$allowed_hosts" ] && ! printf '%s\n' "$allowed_hosts" | grep -Eq '^[][A-Za-z0-9.:,-]+$'; then
    fail "--allowed-host must be a comma-separated list of hosts"
fi
case $env_file in
    /*) ;;
    *) env_file="$PWD/$env_file" ;;
esac
case $env_file in
    "$PWD"/*) env_display=${env_file#"$PWD"/} ;;
    *) env_display=$env_file ;;
esac

command -v docker >/dev/null 2>&1 || fail "docker is not installed or not in PATH"
docker info >/dev/null 2>&1 || fail "cannot reach the Docker daemon; start Docker or check permissions (docker info)"

container_state() {
    docker container inspect -f '{{.State.Status}}' "$container" 2>/dev/null || true
}

container_owned() {
    [ "$(docker container inspect -f '{{index .Config.Labels "io.workbench.dev-db"}}' "$container" 2>/dev/null || true)" = 1 ]
}

volume_exists() {
    docker volume inspect "$volume" >/dev/null 2>&1
}

volume_owned() {
    [ "$(docker volume inspect -f '{{index .Labels "io.workbench.dev-db"}}' "$volume" 2>/dev/null || true)" = 1 ]
}

env_file_generated() {
    [ -f "$env_file" ] && head -n 1 "$env_file" | grep -q "^$marker"
}

published_port() {
    docker container inspect -f '{{range $p, $b := .HostConfig.PortBindings}}{{if eq $p "5432/tcp"}}{{range $b}}{{.HostPort}}{{end}}{{end}}{{end}}' "$container"
}

require_owned_container() {
    if [ -n "$state" ] && ! container_owned; then
        fail "container $container exists but was not created by db-manage.sh; choose another --name"
    fi
}

check_published_port() {
    published=$(published_port)
    if [ "$port_explicit" -eq 1 ] && [ "$published" != "$port" ]; then
        fail "container $container publishes port ${published:-none}, not $port; drop --port or use another --name"
    fi
    port=$published
}

wait_ready() {
    say "waiting for PostgreSQL (up to ${timeout}s)..."
    elapsed=0
    until docker exec "$container" pg_isready -q -h 127.0.0.1 -p 5432 >/dev/null 2>&1; do
        if [ "$(container_state)" != running ]; then
            docker logs --tail 20 "$container" >&2 || true
            fail "container $container stopped while starting"
        fi
        if [ "$elapsed" -ge "$timeout" ]; then
            fail "PostgreSQL was not ready after ${timeout}s; inspect: docker logs $container"
        fi
        sleep 1
        elapsed=$((elapsed + 1))
    done
    say "PostgreSQL is ready on 127.0.0.1:$port"
}

start_container() {
    if [ "$state" = running ]; then
        say "container $container is already running"
    else
        say "starting container $container..."
        docker start "$container" >/dev/null
    fi
}

state=$(container_state)

case $command in
status)
    if [ -z "$state" ]; then
        echo "container: $container (not created)"
    else
        owner="created by db-manage.sh"
        container_owned || owner="NOT created by db-manage.sh"
        echo "container: $container ($state, $owner)"
        echo "image:     $(docker container inspect -f '{{.Config.Image}}' "$container")"
        echo "port:      127.0.0.1:$(published_port)"
        if [ "$state" = running ]; then
            if docker exec "$container" pg_isready -q -h 127.0.0.1 -p 5432 >/dev/null 2>&1; then
                echo "ready:     yes"
            else
                echo "ready:     no"
            fi
        fi
    fi
    if volume_exists; then echo "volume:    $volume (present)"; else echo "volume:    $volume (missing)"; fi
    if env_file_generated; then
        echo "env file:  $env_display (generated, mode $(stat -c %a "$env_file" 2>/dev/null || echo '?'))"
    elif [ -e "$env_file" ]; then
        echo "env file:  $env_display (present, not generated by db-manage.sh)"
    else
        echo "env file:  $env_display (missing)"
    fi
    exit 0
    ;;
stop)
    if [ -z "$state" ]; then
        say "container $container does not exist; nothing to stop"
        exit 0
    fi
    require_owned_container
    if [ "$state" = running ] || [ "$state" = restarting ]; then
        docker stop "$container" >/dev/null
        say "stopped $container (data kept in volume $volume)"
    else
        say "container $container is already stopped ($state)"
    fi
    exit 0
    ;;
start)
    [ -n "$state" ] || fail "container $container does not exist; run: ./scripts/db-manage.sh init"
    require_owned_container
    check_published_port
    start_container
    wait_ready
    exit 0
    ;;
uninit)
    found=0
    echo "db-manage: uninit removes:"
    if [ -n "$state" ]; then echo "  container $container ($state)"; found=1; fi
    if volume_exists; then echo "  volume $volume (all database data)"; found=1; fi
    if env_file_generated; then echo "  env file $env_display"; found=1; fi
    if [ "$found" -eq 0 ]; then
        echo "  (nothing found)"
        exit 0
    fi
    require_owned_container
    if volume_exists && ! volume_owned; then
        fail "volume $volume was not created by db-manage.sh; refusing to remove it"
    fi
    if [ "$yes" -ne 1 ]; then
        if [ -t 0 ]; then
            printf 'Remove these permanently? [y/N] '
            read -r answer || answer=
            case $answer in
                y|Y|yes|YES) ;;
                *) fail "cancelled; nothing removed" ;;
            esac
        else
            fail "nothing removed; confirm with --yes (stdin is not a terminal)"
        fi
    fi
    if [ -n "$state" ]; then
        docker rm -f "$container" >/dev/null
        say "removed container $container"
    fi
    if volume_exists; then
        docker volume rm "$volume" >/dev/null
        say "removed volume $volume"
    fi
    if env_file_generated; then
        rm -f "$env_file"
        say "removed $env_display"
    elif [ -e "$env_file" ]; then
        say "kept $env_display (not generated by this script)"
    fi
    say "local runtime files under $(dirname -- "$data_path") were kept."
    exit 0
    ;;
esac

# init
password_from_env_file() {
    sed -n 's#^WORKBENCH_DATABASE_URL=postgresql://[^:]*:\([A-Za-z0-9]*\)@.*#\1#p' "$env_file" | head -n 1
}

port_in_use() {
    if command -v ss >/dev/null 2>&1; then
        ss -Hltn "( sport = :$1 )" 2>/dev/null | grep -q .
    elif command -v lsof >/dev/null 2>&1; then
        lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1
    else
        return 1
    fi
}

password=
require_owned_container
if [ -z "$state" ] && volume_exists && ! volume_owned; then
    fail "volume $volume exists but was not created by db-manage.sh; choose another --volume"
fi
if [ -n "$state" ] || volume_exists; then
    # Existing database: the password lives in the volume, so reuse the one from the env file.
    if [ ! -f "$env_file" ]; then
        fail "container or volume for $container exists but $env_display is missing.
  Pass the env file that was generated for it with --env-file, or recreate the database
  (deletes its data): ./scripts/db-manage.sh uninit --name $container"
    fi
    password=$(password_from_env_file)
    [ -n "$password" ] || fail "$env_display has no WORKBENCH_DATABASE_URL written by db-manage.sh; pass the matching --env-file"
elif [ -e "$env_file" ] && [ "$force" -ne 1 ]; then
    fail "$env_display already exists but container $container does not; use --force to replace it or --env-file to choose another file"
fi

if [ -n "$state" ]; then
    check_published_port
    start_container
else
    if port_in_use "$port"; then
        fail "port $port on this host is already in use; choose a free port with --port"
    fi
    if [ -z "$password" ]; then
        password=$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 32)
        [ "${#password}" -eq 32 ] || fail "could not generate a random password"
    fi
    volume_exists || docker volume create --label "$label" "$volume" >/dev/null
    say "creating container $container ($image, 127.0.0.1:$port)..."
    # The password reaches docker through the environment, not the command line.
    if ! POSTGRES_PASSWORD=$password docker run -d --name "$container" \
        --label "$label" \
        --restart unless-stopped \
        -e POSTGRES_DB="$db_name" \
        -e POSTGRES_USER="$db_user" \
        -e POSTGRES_PASSWORD \
        -p "127.0.0.1:$port:5432" \
        -v "$volume:/var/lib/postgresql/data" \
        "$image" >/dev/null; then
        docker rm -f "$container" >/dev/null 2>&1 || true
        fail "docker run failed; if the port is taken, choose another with --port"
    fi
fi
wait_ready

setting() {
    if [ -n "$2" ]; then echo "$1=$2"; else echo "# $1="; fi
}

if [ -e "$env_file" ] && [ "$force" -ne 1 ]; then
    say "kept existing $env_display"
    [ "$settings_given" -eq 0 ] || say "run settings were not applied; add --force to rewrite the file (the password is kept)"
else
    mkdir -p "$(dirname -- "$env_file")"
    tmp_file="$env_file.tmp.$$"
    trap 'rm -f "$tmp_file"' EXIT HUP INT TERM
    (
        umask 077
        cat >"$tmp_file" <<ENV
$marker for container $container. Contains a password; keep it private.
# Start: ./scripts/dev.sh --config $env_display
# Precedence: command-line flags > shell environment > this file > defaults.

# Database. Native processes reach PostgreSQL on 127.0.0.1; inside Compose the host is \`postgres\`.
WORKBENCH_DB_DRIVER=postgres
WORKBENCH_DATABASE_URL=postgresql://$db_user:$password@127.0.0.1:$port/$db_name?sslmode=disable
# Local runtime files (OpenD, chart cache) for this workspace.
WORKBENCH_DATA=$data_path

# Go backend and Vite.
WORKBENCH_AUTH=$auth
WORKBENCH_LISTEN=$listen
WORKBENCH_DEV_WEB_PORT=$web_port
# WORKBENCH_LOG_LEVEL=debug

# HTTPS reverse proxy in front of Vite; it should forward to 127.0.0.1:$web_port.
$(setting WORKBENCH_PUBLIC_URL "$public_url")
$(setting WORKBENCH_ALLOWED_HOSTS "$allowed_hosts")
ENV
    )
    chmod 600 "$tmp_file"
    mv "$tmp_file" "$env_file"
    trap - EXIT HUP INT TERM
    say "wrote $env_display (mode 600)"
fi
case $env_file in
    "$repo_root"/*)
        if command -v git >/dev/null 2>&1 && ! git -C "$repo_root" check-ignore -q "$env_file"; then
            echo "db-manage: warning: $env_display is not ignored by Git; do not commit it" >&2
        fi
        ;;
esac

cat <<NEXT

Next steps:
  ./scripts/dev.sh --config $env_display --print-config
  ./scripts/dev.sh --config $env_display

This is a new, empty workspace. The first start in password mode prints the initial
password once in the log; data from SQLite workspaces is not copied.
Stop or remove later: ./scripts/db-manage.sh stop | uninit (add the same --name/--env-file)
NEXT
